(function () {
  const dict = window.TM_I18N;
  let currentLang = localStorage.getItem('tmaxos_lang') || 'en';
  const textDefaults = new Map();
  const placeholderDefaults = new Map();
  const ariaDefaults = new Map();
  const titleDefaults = new Map();

  function apply(lang) {
    const map = dict[lang] || {};
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      if (!textDefaults.has(el)) textDefaults.set(el, el.textContent.trim());
      const val = map[el.dataset.i18n];
      if (lang === 'en') {
        if (el.textContent.trim() !== textDefaults.get(el)) el.textContent = textDefaults.get(el);
      } else if (val !== undefined && el.textContent.trim() !== val) {
        el.textContent = val;
      }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      if (!placeholderDefaults.has(el)) placeholderDefaults.set(el, el.getAttribute('placeholder'));
      const val = map[el.dataset.i18nPlaceholder];
      el.setAttribute('placeholder', lang === 'en' ? placeholderDefaults.get(el) || '' : (val !== undefined ? val : placeholderDefaults.get(el) || ''));
    });
    document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      if (!ariaDefaults.has(el)) ariaDefaults.set(el, el.getAttribute('aria-label'));
      const val = map[el.dataset.i18nAria];
      el.setAttribute('aria-label', lang === 'en' ? ariaDefaults.get(el) || '' : (val !== undefined ? val : ariaDefaults.get(el) || ''));
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      if (!titleDefaults.has(el)) titleDefaults.set(el, el.getAttribute('title'));
      const val = map[el.dataset.i18nTitle];
      el.setAttribute('title', lang === 'en' ? titleDefaults.get(el) || '' : (val !== undefined ? val : titleDefaults.get(el) || ''));
    });
    document.documentElement.lang = lang === 'my' ? 'my' : 'en';
  }

  function set(lang) {
    currentLang = lang;
    localStorage.setItem('tmaxos_lang', lang);
    apply(lang);
  }

  window.TM_LANG = {
    apply,
    set,
    toggle: () => set(currentLang === 'en' ? 'my' : 'en'),
    current: () => currentLang,
  };

  const toggle = document.getElementById('langToggle');
  if (toggle) toggle.addEventListener('click', () => TM_LANG.toggle());
  apply(currentLang);
})();